/// Domain models of WirdiApp. Plain immutable classes with JSON mapping.
library;

enum ProgramType { memorization, revision }

enum ExamStatus { scheduled, passed, failed }

enum EventType { program, progress, exam, student }

class Group {
  const Group({required this.id, required this.name, this.supervisor = ''});

  final String id;
  final String name;
  final String supervisor;

  Group copyWith({String? name, String? supervisor}) =>
      Group(id: id, name: name ?? this.name, supervisor: supervisor ?? this.supervisor);

  Map<String, dynamic> toJson() => {'id': id, 'name': name, 'supervisor': supervisor};

  factory Group.fromJson(Map<String, dynamic> j) =>
      Group(id: j['id'] as String, name: j['name'] as String, supervisor: (j['supervisor'] ?? '') as String);
}

class Student {
  const Student({
    required this.id,
    required this.name,
    required this.email,
    required this.accessCode,
    this.phone = '',
    this.groupId,
  });

  final String id;
  final String name;
  final String email;
  final String phone;
  final String? groupId;

  /// 6-digit code the student uses to sign in (generated by the supervisor).
  final String accessCode;

  String get initials {
    final parts = name.trim().split(RegExp(r'\s+')).where((p) => p.isNotEmpty).toList();
    if (parts.isEmpty) return '؟';
    return parts.length == 1 ? parts.first.substring(0, 1) : '${parts[0][0]} ${parts[1][0]}';
  }

  Student copyWith({String? name, String? email, String? phone, String? groupId, bool clearGroup = false}) =>
      Student(
        id: id,
        name: name ?? this.name,
        email: email ?? this.email,
        phone: phone ?? this.phone,
        groupId: clearGroup ? null : (groupId ?? this.groupId),
        accessCode: accessCode,
      );

  Map<String, dynamic> toJson() =>
      {'id': id, 'name': name, 'email': email, 'phone': phone, 'groupId': groupId, 'accessCode': accessCode};

  factory Student.fromJson(Map<String, dynamic> j) => Student(
        id: j['id'] as String,
        name: j['name'] as String,
        email: j['email'] as String,
        phone: (j['phone'] ?? '') as String,
        groupId: j['groupId'] as String?,
        accessCode: j['accessCode'] as String,
      );
}

/// A memorization (حفظ) or revision (مراجعة) programme for one student.
class Program {
  const Program({
    required this.id,
    required this.studentId,
    required this.type,
    required this.title,
    required this.totalUnits,
    this.doneUnits = 0,
    this.deadline,
    this.notes = '',
  });

  final String id;
  final String studentId;
  final ProgramType type;

  /// e.g. "سورة البقرة" or "جزء عمّ".
  final String title;

  /// Number of pages (or verses) to complete.
  final int totalUnits;
  final int doneUnits;
  final DateTime? deadline;
  final String notes;

  double get progress => totalUnits <= 0 ? 0 : (doneUnits / totalUnits).clamp(0, 1).toDouble();
  bool get isDone => doneUnits >= totalUnits && totalUnits > 0;

  /// Late or close to the deadline while far from done.
  bool isAtRisk(DateTime now) {
    if (isDone || deadline == null) return false;
    final daysLeft = deadline!.difference(now).inDays;
    return daysLeft < 0 || (daysLeft <= 7 && progress < 0.8);
  }

  Program copyWith({String? title, int? totalUnits, int? doneUnits, DateTime? deadline, String? notes, String? studentId, ProgramType? type}) =>
      Program(
        id: id,
        studentId: studentId ?? this.studentId,
        type: type ?? this.type,
        title: title ?? this.title,
        totalUnits: totalUnits ?? this.totalUnits,
        doneUnits: (doneUnits ?? this.doneUnits).clamp(0, totalUnits ?? this.totalUnits),
        deadline: deadline ?? this.deadline,
        notes: notes ?? this.notes,
      );

  Map<String, dynamic> toJson() => {
        'id': id,
        'studentId': studentId,
        'type': type.name,
        'title': title,
        'totalUnits': totalUnits,
        'doneUnits': doneUnits,
        'deadline': deadline?.toIso8601String(),
        'notes': notes,
      };

  factory Program.fromJson(Map<String, dynamic> j) => Program(
        id: j['id'] as String,
        studentId: j['studentId'] as String,
        type: ProgramType.values.byName(j['type'] as String),
        title: j['title'] as String,
        totalUnits: j['totalUnits'] as int,
        doneUnits: (j['doneUnits'] ?? 0) as int,
        deadline: j['deadline'] == null ? null : DateTime.parse(j['deadline'] as String),
        notes: (j['notes'] ?? '') as String,
      );
}

class Exam {
  const Exam({
    required this.id,
    required this.studentId,
    required this.title,
    required this.date,
    this.status = ExamStatus.scheduled,
    this.grade,
    this.notes = '',
  });

  final String id;
  final String studentId;
  final String title;
  final DateTime date;
  final ExamStatus status;

  /// Mark out of 20, set when the result is recorded.
  final double? grade;
  final String notes;

  bool get isUpcoming => status == ExamStatus.scheduled;

  Exam copyWith({String? title, DateTime? date, ExamStatus? status, double? grade, String? notes, String? studentId}) => Exam(
        id: id,
        studentId: studentId ?? this.studentId,
        title: title ?? this.title,
        date: date ?? this.date,
        status: status ?? this.status,
        grade: grade ?? this.grade,
        notes: notes ?? this.notes,
      );

  Map<String, dynamic> toJson() => {
        'id': id,
        'studentId': studentId,
        'title': title,
        'date': date.toIso8601String(),
        'status': status.name,
        'grade': grade,
        'notes': notes,
      };

  factory Exam.fromJson(Map<String, dynamic> j) => Exam(
        id: j['id'] as String,
        studentId: j['studentId'] as String,
        title: j['title'] as String,
        date: DateTime.parse(j['date'] as String),
        status: ExamStatus.values.byName(j['status'] as String),
        grade: (j['grade'] as num?)?.toDouble(),
        notes: (j['notes'] ?? '') as String,
      );
}

/// Activity feed entry shown as a notification.
class AppEvent {
  const AppEvent({required this.id, required this.type, required this.message, required this.date, this.studentId});

  final String id;
  final EventType type;
  final String message;
  final DateTime date;

  /// Null = visible to the supervisor only.
  final String? studentId;

  Map<String, dynamic> toJson() =>
      {'id': id, 'type': type.name, 'message': message, 'date': date.toIso8601String(), 'studentId': studentId};

  factory AppEvent.fromJson(Map<String, dynamic> j) => AppEvent(
        id: j['id'] as String,
        type: EventType.values.byName(j['type'] as String),
        message: j['message'] as String,
        date: DateTime.parse(j['date'] as String),
        studentId: j['studentId'] as String?,
      );
}

/// The association using the app and its supervisor account.
class Association {
  const Association({required this.name, required this.supervisorName, required this.pin});

  final String name;
  final String supervisorName;

  /// 4-digit PIN protecting the supervisor space on this device.
  final String pin;

  Map<String, dynamic> toJson() => {'name': name, 'supervisorName': supervisorName, 'pin': pin};

  factory Association.fromJson(Map<String, dynamic> j) =>
      Association(name: j['name'] as String, supervisorName: j['supervisorName'] as String, pin: j['pin'] as String);
}
